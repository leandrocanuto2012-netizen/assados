'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
const router=fs.readFileSync(__dirname+'/gestao-router.js','utf8');
const sql=fs.readFileSync(__dirname+'/03-modulos-gestao.sql','utf8');
const html=fs.readFileSync(__dirname+'/public/modulos-gestao.html','utf8');
for(const route of ['/dashboard/meu-painel','/dashboard/filiais','/contabilidade/lancamentos','/edras/movimentos','/juridico/processos','/juridico/prazos']) assert.ok(router.includes(route),`Rota ausente: ${route}`);
for(const table of ['gestao_lancamentos_contabeis','edras_movimentos','juridico_processos','juridico_prazos','juridico_documentos','gestao_auditoria']) assert.ok(sql.includes('public.'+table),`Tabela ausente: ${table}`);
assert.ok(sql.includes('enable row level security'),'RLS não habilitado');
assert.ok(router.includes("eq('usuario_id',userId(req))"),'Escopo individual do EDRAS ausente');
assert.ok(router.includes("eq('status','rascunho')"),'Proteção de edição/exclusão de lançamentos confirmados ausente');
for(const name of ['Filiais','Contabilidade','EDRAS','Jurídico']) assert.ok(html.includes(name),`Tela ausente: ${name}`);
assert.ok(html.includes('/dashboard/meu-painel'),'Painel do usuário ausente');
console.log('OK: verificações estáticas dos módulos concluídas.');
